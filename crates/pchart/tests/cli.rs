#[test]
fn every_view_exports_and_light_pages_refuse_terminal_options() {
    let path = copy("views");
    let svg = path.with_file_name("view.svg");
    for (view, style) in [("gantt", None), ("phases", None), ("now-next-later", None), ("milestones", None), ("structure", None), ("network", None), ("matrix", None), ("roadmap", Some("light")), ("roadmap", None)] {
        let mut args = vec!["export", path.to_str().unwrap(), "--view", view, "--svg", svg.to_str().unwrap()];
        if let Some(style) = style {
            args.extend(["--style", style]);
        }
        let output = pchart(&args, None);
        assert!(output.status.success(), "{view} {style:?}: {}", String::from_utf8_lossy(&output.stderr));
        assert!(std::fs::read_to_string(&svg).unwrap().starts_with("<svg"), "{view}");
    }
    for args in [vec!["--view", "gantt", "--style", "dark"], vec!["--view", "roadmap", "--style", "light", "--level", "full"], vec!["--view", "timeline"]] {
        let mut all = vec!["export", path.to_str().unwrap(), "--svg", svg.to_str().unwrap()];
        all.extend(args.iter().copied());
        assert_eq!(pchart(&all, None).status.code(), Some(3), "{args:?}");
    }
}

#[test]
fn an_audience_sees_only_what_is_meant_for_it() {
    let path = copy("audience");
    let svg = path.with_file_name("gantt.svg");
    let page = |audience: &str| {
        let output = pchart(&["export", path.to_str().unwrap(), "--view", "gantt", "--audience", audience, "--svg", svg.to_str().unwrap()], None);
        assert!(output.status.success(), "{}", String::from_utf8_lossy(&output.stderr));
        std::fs::read_to_string(&svg).unwrap()
    };
    let (team, management, client) = (page("team"), page("management"), page("client"));
    assert!(team.contains("To spare") && team.contains("no buffer"));
    assert!(management.contains("To spare") && !management.contains("no buffer"));
    assert!(!client.contains("To spare") && !client.contains("no buffer") && !client.contains("wd to spare"));
    let output = pchart(&["export", path.to_str().unwrap(), "--audience", "boss", "--svg", svg.to_str().unwrap()], None);
    assert_eq!(output.status.code(), Some(3));
}

#[test]
fn a_new_plan_comes_from_a_template_and_never_replaces_a_file() {
    let dir = copy("new").parent().unwrap().to_path_buf();
    let path = dir.join("portal-v2.pchart");
    let written = pchart(&["new", path.to_str().unwrap(), "--template", "new-application", "--name", "Customer portal v2", "--target", "2027-03-01"], None);
    assert!(written.status.success(), "{}", String::from_utf8_lossy(&written.stderr));
    assert!(stdout(&written).starts_with("Saved.\nLaunch on Mon 01 Mar is on track."), "{}", stdout(&written));
    let text = std::fs::read_to_string(&path).unwrap();
    assert!(text.contains("name = \"Customer portal v2\"") && text.contains("on = 2027-03-01"), "{text}");

    let again = pchart(&["new", path.to_str().unwrap(), "--template", "empty"], None);
    assert_eq!(again.status.code(), Some(4));
    assert!(String::from_utf8_lossy(&again.stderr).contains("portal-v2.pchart: is there already"));
    assert_eq!(std::fs::read_to_string(&path).unwrap(), text);

    let unknown = pchart(&["new", dir.join("x.pchart").to_str().unwrap(), "--template", "trade-fair"], None);
    assert_eq!(unknown.status.code(), Some(3));
    assert!(String::from_utf8_lossy(&unknown.stderr).starts_with("there is no template \"trade-fair\"; there are new-application, website-relaunch, product-launch, empty"));

    let web = dir.join("web.pchart");
    let dry = pchart(&["new", web.to_str().unwrap(), "--template", "website-relaunch", "--start", "2026-11-02", "--dry-run", "--json"], None);
    let value: serde_json::Value = serde_json::from_str(&stdout(&dry)).unwrap();
    assert_eq!(value["written"], false);
    assert!(!web.exists());
    let forwards = pchart(&["new", web.to_str().unwrap(), "--template", "website-relaunch", "--start", "2026-11-02"], None);
    assert!(forwards.status.success());
    assert!(std::fs::read_to_string(&web).unwrap().contains("start = 2026-11-02"));
}

